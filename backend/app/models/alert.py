class ImportHistory(Base):
    """
    Page 10: Import History table stored in PostgreSQL/SQLite per Workspace ID.
    """
    __tablename__ = "import_history"

    id = Column(Integer, primary_key=True, index=True)
    import_code = Column(String(32), index=True, nullable=False)  # e.g., IMP-0001
    workspace_id = Column(
        String(64),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
        default="ws-default-001",
    )
    source_type = Column(String(64), nullable=False)
    filename = Column(String(255), nullable=False)
    total_events = Column(Integer, default=0, nullable=False)
    new_events = Column(Integer, default=0, nullable=False)
