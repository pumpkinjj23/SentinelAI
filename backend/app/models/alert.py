import uuid
from datetime import datetime, timezone
from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    JSON,
    String,
    Text,
)
from sqlalchemy.orm import relationship
from app.core.database import Base


def utc_now():
    return datetime.now(timezone.utc)


def new_uuid_str() -> str:
    return str(uuid.uuid4())


class User(Base):
    """
    Stores SOC user identities verified via Passwordless Email Authentication / Invitation links.
    No passwords required.
    """
    __tablename__ = "users"

    id = Column(String(64), primary_key=True, default=new_uuid_str, index=True)
    email = Column(String(180), unique=True, index=True, nullable=False)
    display_name = Column(String(128), nullable=False)
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)
    last_active_at = Column(DateTime(timezone=True), default=utc_now, onupdate=utc_now, nullable=False)

    memberships = relationship(
        "WorkspaceMember",
        back_populates="user",
        cascade="all, delete-orphan",
    )


class Workspace(Base):
    """
    SentinelAI SOC Collaboration Workspace (Room).
    Has a Workspace Owner and invited Members (Owner / Analyst / Viewer).
    """
    __tablename__ = "workspaces"

    id = Column(String(64), primary_key=True, default=new_uuid_str, index=True)
    workspace_code = Column(String(32), unique=True, index=True, nullable=False)  # e.g., SNT-WS-001
    name = Column(String(150), nullable=False)
    description = Column(Text, nullable=True)
    owner_user_id = Column(String(64), ForeignKey("users.id", ondelete="SET NULL"), index=True, nullable=True)
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)
    updated_at = Column(DateTime(timezone=True), default=utc_now, onupdate=utc_now, nullable=False)

    members = relationship(
        "WorkspaceMember",
        back_populates="workspace",
        cascade="all, delete-orphan",
    )
    invitations = relationship(
        "WorkspaceInvitation",
        back_populates="workspace",
        cascade="all, delete-orphan",
    )
    alerts = relationship(
        "SecurityAlert",
        back_populates="workspace",
        cascade="all, delete-orphan",
    )
    audit_logs = relationship(
        "AuditLog",
        back_populates="workspace",
        cascade="all, delete-orphan",
    )
    import_histories = relationship(
        "ImportHistory",
        back_populates="workspace",
        cascade="all, delete-orphan",
    )


class WorkspaceMember(Base):
    """
    Links a User to a Workspace with a specific Role:
    - OWNER: Full workspace, member, invitation, alert, AI, review, and audit control
    - ANALYST: View dashboard/alerts, import alerts, run AI analysis, approve/reject alerts, view audit logs
    - VIEWER: Read-only access to Dashboard and Security Alerts
    """
    __tablename__ = "workspace_members"

    id = Column(Integer, primary_key=True, index=True)
    workspace_id = Column(
        String(64),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    user_id = Column(
        String(64),
        ForeignKey("users.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    role = Column(String(32), default="ANALYST", nullable=False)  # OWNER | ANALYST | VIEWER
    status = Column(String(32), default="ACTIVE", nullable=False)  # ACTIVE | SUSPENDED
    joined_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)

    workspace = relationship("Workspace", back_populates="members")
    user = relationship("User", back_populates="memberships")


class WorkspaceInvitation(Base):
    """
    Stores single-use, time-limited invitation tokens generated by the Workspace Owner.
    """
    __tablename__ = "workspace_invitations"

    id = Column(Integer, primary_key=True, index=True)
    invite_code = Column(String(32), unique=True, index=True, nullable=False)  # e.g., INV-0001
    workspace_id = Column(
        String(64),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    invited_email = Column(String(180), index=True, nullable=False)
    role = Column(String(32), default="ANALYST", nullable=False)  # ANALYST | VIEWER | OWNER
    token = Column(String(128), unique=True, index=True, nullable=False)  # Single-use random token
    status = Column(String(32), default="PENDING", nullable=False)  # PENDING | ACCEPTED | REVOKED | EXPIRED
    invited_by_email = Column(String(180), nullable=False)
    expires_at = Column(DateTime(timezone=True), nullable=False)
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)
    accepted_at = Column(DateTime(timezone=True), nullable=True)

    workspace = relationship("Workspace", back_populates="invitations")


class SecurityAlert(Base):
    """
    Stores normalized security alerts and raw source evidence scoped to a specific workspace_id.
    """
    __tablename__ = "security_alerts"

    id = Column(Integer, primary_key=True, index=True)
    workspace_id = Column(
        String(64),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
        default="ws-default-001",
    )
    alert_code = Column(String(64), unique=True, index=True, nullable=False)  # e.g., ALT-0001
    external_id = Column(String(128), index=True, nullable=True)
    dedup_hash = Column(String(128), unique=True, index=True, nullable=False)
    occurrence_count = Column(Integer, default=1, nullable=False)

    # Normalized metadata
    source = Column(String(64), default="Wazuh", nullable=False)
    timestamp = Column(DateTime(timezone=True), default=utc_now, nullable=False)
    rule_id = Column(String(64), nullable=True)
    rule_level = Column(Integer, default=5, nullable=False)
    description = Column(Text, nullable=False)

    # Normalized Network / Host / Process / IOC entities
    hostname = Column(String(128), nullable=True)
    src_ip = Column(String(64), nullable=True, index=True)
    dst_ip = Column(String(64), nullable=True)
    username = Column(String(128), nullable=True)
    process_name = Column(String(128), nullable=True)
    command_line = Column(Text, nullable=True)
    domain = Column(String(255), nullable=True)
    file_hash = Column(String(128), nullable=True)
    protocol = Column(String(32), nullable=True)

    # Original immutable evidence
    raw_log = Column(Text, nullable=False)
    raw_payload = Column(JSON, nullable=False)

    # Triage & Workflow Status
    status = Column(String(32), default="PENDING_REVIEW", index=True, nullable=False)
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)
    updated_at = Column(DateTime(timezone=True), default=utc_now, onupdate=utc_now, nullable=False)

    # Relationships
    workspace = relationship("Workspace", back_populates="alerts")
    analysis = relationship(
        "AlertAnalysis",
        back_populates="alert",
        uselist=False,
        cascade="all, delete-orphan",
    )
    reviews = relationship(
        "AnalystReviewRecord",
        back_populates="alert",
        cascade="all, delete-orphan",
        order_by="AnalystReviewRecord.created_at.desc()",
    )
    audit_logs = relationship(
        "AuditLog",
        back_populates="alert",
        cascade="all, delete-orphan",
        order_by="AuditLog.created_at.desc()",
    )


class AlertAnalysis(Base):
    """
    Stores Rule Engine Risk Score, IOC Enrichment, MITRE ATT&CK Mappings, and AI Analysis
    scoped to a specific workspace_id.
    """
    __tablename__ = "alert_analyses"

    id = Column(Integer, primary_key=True, index=True)
    workspace_id = Column(
        String(64),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
        default="ws-default-001",
    )
    alert_id = Column(
        Integer,
        ForeignKey("security_alerts.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
    )

    risk_score = Column(Integer, nullable=False)
    severity = Column(String(32), index=True, nullable=False)
    incident_type = Column(String(128), nullable=False)
    scoring_breakdown = Column(JSON, nullable=False)
    ioc_results = Column(JSON, nullable=False)
    mitre_mapping = Column(JSON, nullable=False)

    ai_provider = Column(String(64), default="mock", nullable=False)
    ai_summary = Column(Text, nullable=False)
    behavior_analysis = Column(Text, nullable=False)
    risk_justification = Column(Text, nullable=False)
    evidence_citations = Column(JSON, nullable=False)
    recommendations = Column(JSON, nullable=False)
    is_suspicious = Column(Boolean, default=True, nullable=False)
    requires_analyst_review = Column(Boolean, default=True, nullable=False)

    analysis_duration_ms = Column(Float, default=0.0, nullable=False)
    analyzed_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)

    alert = relationship("SecurityAlert", back_populates="analysis")


